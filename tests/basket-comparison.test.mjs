import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compareBasket,parseBasket,serializeBasket} from '../lib/basket-comparison.mjs';
import {nearestPerChain} from '../lib/nearby.mjs';
const read=file=>JSON.parse(readFileSync(new URL(file,import.meta.url),'utf8'));
const live=read('../data/live.json'),geo=read('../data/store-geo.json'),places=read('../data/places.json');
const stores=nearestPerChain(live.stores.map(s=>({...s,...geo[s.id]})),places.cities.tampa,20);
// Fixed observation time keeps this snapshot regression independent of wall-clock expiry.
const now=Math.max(...live.products.flatMap(p=>p.offers.map(o=>Date.parse(o.observedAt))))+1000;
const milk='mercato:34017',butter='mercato:4054',berries='mercato:94963';
const basket={[milk]:1,[butter]:1,[berries]:1};
const quote=(result,id)=>result.totals.find(t=>t.store.id===id);
const result=compareBasket(live.products,basket,stores,now);
assert.equal(result.lineCount,3);assert.equal(result.itemCount,3);
assert.equal(quote(result,'mercato:1323').cents,2057);
assert.equal(quote(result,'mercato:1323').complete,true);
assert.equal(quote(result,'mercato:2701').cents,1408);
assert.equal(quote(result,'mercato:2701').complete,false);
assert.deepEqual(quote(result,'mercato:2701').missingIds,[berries]);
assert.equal(quote(result,'target:656').cents,null,'Missing prices must not become $0 totals');
assert.deepEqual(result.bestFullStoreIds,[],'One complete quote cannot establish the lowest basket');
assert.deepEqual(result.shared.rows.map(r=>r.id),[milk,butter]);
assert.deepEqual(result.shared.stores.map(s=>s.cents),[1408,1440]);
assert.equal(result.shared.savingsCents,32);
const more=compareBasket(live.products,{...basket,[butter]:2},stores,now);
assert.equal(more.itemCount,4);assert.equal(quote(more,'mercato:1323').cents,2777);
assert.equal(quote(more,'mercato:2701').cents,2087);
assert.deepEqual(more.shared.stores.map(s=>s.cents),[2087,2160]);
const two=compareBasket(live.products,{[milk]:1,[butter]:1},stores,now);
assert.equal(two.pricedStores.filter(s=>s.complete).length,2);
assert.deepEqual(two.bestFullStoreIds,['mercato:2701']);
assert.equal(two.shared.rows.length,two.rows.length);
const narrower=compareBasket(live.products,basket,stores.filter(s=>s.chain==='Target'),now);
assert.equal(narrower.pricedStores.length,0,'Never borrow quotes from branches outside the chosen location');
assert.equal(narrower.itemCount,3,'Unavailable basket items must remain selected');
const stale=compareBasket(live.products,basket,stores,now+86400000);
assert.equal(stale.pricedStores.length,0);assert.equal(stale.shared.stores.length,0);
assert(stale.totals.every(t=>t.cents===null&&!t.complete));
assert.equal(compareBasket(live.products,{},stores,now).pricedStores.length,0);
assert.deepEqual(parseBasket(serializeBasket(basket),live.products),basket);
assert.deepEqual(parseBasket(`${milk}~0,${butter}~1.5,${berries}~100,no-such-product~1`,live.products),{});
assert.deepEqual(parseBasket([`${milk}~1`],live.products),{});
const large=Object.fromEntries(live.products.slice(0,60).map(p=>[p.id,1]));
assert.equal(Object.keys(parseBasket(serializeBasket(large),live.products)).length,60);
assert.equal(compareBasket(live.products,large,stores,now).lineCount,60,'Large baskets must never silently drop items');
const syntheticStores=['a','b','c'].map(id=>({id,name:id}));
const offer=(storeId,cents)=>({storeId,cents,available:true,observedAt:new Date(now-1000).toISOString()});
const synthetic=[{id:'one',name:'One',offers:[offer('a',100),offer('b',110),offer('c',1)]},{id:'two',name:'Two',offers:[offer('a',200),offer('b',190)]},{id:'three',name:'Three',offers:[offer('c',100)]}];
const shared=compareBasket(synthetic,{one:1,two:2,three:1},syntheticStores,now);
assert.deepEqual(shared.shared.rows.map(r=>r.id),['one','two'],'Choose the largest shared selection, not the one advertising the biggest saving');
assert.deepEqual(shared.shared.stores.map(s=>s.cents),[490,500]);
const tied=compareBasket(synthetic.slice(0,2),{one:1,two:1},syntheticStores,now);
assert.deepEqual(tied.bestFullStoreIds,['a','b']);
console.log('Basket calculations passed: real three-product basket, quantities, full/partial coverage, shared items, location scope, expiry, ties and URL persistence.');
